//! Renders a fully annotated `config.toml` for `sobre config init`.
//!
//! The body is the verbatim [`toml::to_string_pretty`] serialization of the
//! supplied [`Config`], so every field round-trips exactly — independent of
//! schema completeness. Schema descriptions, allowed values and defaults
//! are then woven in as `#` comment lines *above* each key and section, and
//! every key the body leaves out (an unset optional) is listed commented out
//! where uncommenting it alone sets it. Only comment lines and empty section
//! headers are inserted; key/value lines are never touched, which guarantees
//! `parse(render(cfg)) == cfg` and keeps the output a deterministic function
//! of `(cfg, schema)`.

use super::Config;
use super::schema::{ConfigSchema, KeySchema};

const HEADER: &str = "\
# sobre configuration — full annotated reference
#
# Generated by `sobre config init`. Every key is documented with its
# purpose and, where applicable, its default and allowed values. The values
# below are your current configuration; a key you have not set is listed
# commented out — remove the `# ` to set it.
#
# A key left at its default may be deleted — sobre falls back to the documented
# default. Edits apply on the next tool call; the proxy reads them on
# `sobre proxy restart`.

";

/// Builds the annotated `config.toml` text for `cfg`, documented via `schema`.
pub fn render_annotated_config(cfg: &Config, schema: &ConfigSchema) -> String {
    let mut out = String::from(HEADER);

    // Serializing the full config is what guarantees a lossless round-trip; the
    // annotation pass below only ever *inserts* comment lines and empty section
    // headers. A `Config` always serializes, so the error path is unreachable
    // in practice — we still return a valid (header-only) document rather than
    // panicking.
    let Ok(body) = toml::to_string_pretty(cfg) else {
        return out;
    };
    let body = with_every_section_header(&body, schema);
    let tables: Vec<String> = body.lines().filter_map(section_header).collect();

    let mut current_section = String::from("root");
    let mut seen_keys: Vec<String> = Vec::new();
    for line in body.lines() {
        let trimmed = line.trim_start();

        if let Some(section) = section_header(trimmed) {
            append_unset_keys(&mut out, schema, &current_section, &seen_keys, &tables);
            append_section(&mut out, schema, &section, line);
            current_section = section;
            continue;
        }

        if let Some(field) = leading_key(trimmed) {
            let path = if current_section == "root" {
                field.to_string()
            } else {
                format!("{current_section}.{field}")
            };
            if let Some(key_schema) = schema.lookup(&path) {
                append_key_comment(&mut out, key_schema);
            }
            seen_keys.push(path);
        }

        out.push_str(line);
        out.push('\n');
    }
    append_unset_keys(&mut out, schema, &current_section, &seen_keys, &tables);
    out
}

/// `body` with a header for every section of the schema, empty when the
/// config sets nothing in it. `toml` writes no `[proxy]` when the table has
/// no key of its own; a commented `# port = …` would then land under
/// whatever table came last once uncommented. A missing header goes before
/// the section's first sub-table (`[proxy.upstreams]`), or at the end.
fn with_every_section_header(body: &str, schema: &ConfigSchema) -> String {
    let mut lines: Vec<String> = body.lines().map(str::to_string).collect();
    for name in schema.sections.keys().filter(|n| *n != "root") {
        if lines
            .iter()
            .any(|l| section_header(l).as_deref() == Some(name))
        {
            continue;
        }
        let sub = format!("[{name}.");
        if let Some(at) = lines.iter().position(|l| l.starts_with(&sub)) {
            lines.insert(at, format!("[{name}]"));
        } else {
            if lines.last().is_some_and(|l| !l.is_empty()) {
                lines.push(String::new());
            }
            lines.push(format!("[{name}]"));
        }
    }
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

/// The keys of `section` the body did not write, documented and commented
/// out, so that uncommenting any one of them alone sets it:
///
/// - a dotted key of the schema (`upstreams.anthropic` in `[proxy]`) is
///   written as is, unless its sub-table (`[proxy.upstreams]`) is in the
///   body, where it goes instead;
/// - in such a sub-table, the parent's keys under it, without the prefix
///   (`# openai = …`).
fn append_unset_keys(
    out: &mut String,
    schema: &ConfigSchema,
    section: &str,
    seen: &[String],
    tables: &[String],
) {
    let (owner, prefix) = match schema.sections.get(section) {
        Some(_) => (section, String::new()),
        None => match section.split_once('.') {
            Some((parent, sub)) => (parent, format!("{sub}.")),
            None => return,
        },
    };
    let Some(owner_schema) = schema.sections.get(owner) else {
        return;
    };
    // The body's blank line before the next table goes after these keys.
    let spaced = out.ends_with("\n\n");
    if spaced {
        out.pop();
    }
    for (field, key_schema) in &owner_schema.keys {
        let path = if owner == "root" {
            field.clone()
        } else {
            format!("{owner}.{field}")
        };
        if seen.contains(&path) {
            continue;
        }
        let shown = if prefix.is_empty() {
            if let Some((sub, _)) = field.split_once('.')
                && tables.contains(&format!("{owner}.{sub}"))
            {
                continue;
            }
            field.as_str()
        } else {
            match field.strip_prefix(&prefix) {
                Some(rest) => rest,
                None => continue,
            }
        };
        append_key_comment(out, key_schema);
        out.push_str(&format!(
            "# {shown} = <{}>\n",
            key_schema.ty.trim_end_matches('?')
        ));
    }
    if spaced {
        out.push('\n');
    }
}

/// Returns the section name for a `[section]` header line, or `None`. Array-of-
/// tables headers (`[[…]]`) are deliberately ignored (Config has none).
fn section_header(trimmed: &str) -> Option<String> {
    if trimmed.starts_with("[[") || !trimmed.starts_with('[') || !trimmed.ends_with(']') {
        return None;
    }
    let inner = trimmed[1..trimmed.len() - 1].trim();
    if inner.is_empty() {
        None
    } else {
        Some(inner.to_string())
    }
}

/// Extracts the bare key of a `key = value` line. Returns `None` for array
/// continuation lines, closing brackets, or quoted/dotted dynamic-map keys, all
/// of which are passed through verbatim (keeping the round-trip exact).
fn leading_key(trimmed: &str) -> Option<&str> {
    let eq = trimmed.find('=')?;
    let key = trimmed[..eq].trim();
    if !key.is_empty()
        && key
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.'))
    {
        Some(key)
    } else {
        None
    }
}

fn append_section(out: &mut String, schema: &ConfigSchema, section: &str, header_line: &str) {
    if !out.ends_with("\n\n") {
        out.push('\n');
    }
    if let Some(section_schema) = schema.sections.get(section)
        && !section_schema.description.is_empty()
    {
        for comment in section_schema.description.lines() {
            out.push_str("# ");
            out.push_str(comment);
            out.push('\n');
        }
    }
    out.push_str(header_line);
    out.push('\n');
}

fn append_key_comment(out: &mut String, key_schema: &KeySchema) {
    for comment in key_schema.description.lines() {
        out.push_str("# ");
        out.push_str(comment);
        out.push('\n');
    }
    if !key_schema.default.is_null() {
        out.push_str("#   default: ");
        out.push_str(&key_schema.default.to_string());
        out.push('\n');
    }
    if let Some(values) = &key_schema.values
        && !values.is_empty()
    {
        out.push_str("#   values: ");
        out.push_str(&values.join(", "));
        out.push('\n');
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn customized() -> Config {
        let mut cfg = Config {
            compression_level: 0.5,
            debug_log: true,
            ..Config::default()
        };
        cfg.proxy.port = Some(4444);
        cfg.proxy.upstreams.insert(
            "anthropic".to_string(),
            "https://upstream.example".to_string(),
        );
        cfg.ignore = vec!["vendor/**".to_string()];
        cfg
    }

    // Core safety net: rendering then parsing must reproduce the config
    // exactly, regardless of how complete the schema is. The comparison goes
    // through `toml::Value` (map equality is order-independent) so it is robust
    // against `HashMap` iteration order in fields like `tool_total_limits`.
    #[test]
    fn render_round_trips_to_identical_config() {
        let cfg = customized();
        let schema = ConfigSchema::generate();

        let rendered = render_annotated_config(&cfg, &schema);

        let expected: toml::Value = toml::from_str(&toml::to_string_pretty(&cfg).unwrap()).unwrap();
        let actual: toml::Value = toml::from_str(&rendered).expect("rendered config must parse");

        assert_eq!(
            actual, expected,
            "render → parse must reproduce the config exactly"
        );
    }

    #[test]
    fn render_preserves_customized_values() {
        let cfg = customized();
        let schema = ConfigSchema::generate();

        let parsed: Config = toml::from_str(&render_annotated_config(&cfg, &schema)).unwrap();

        assert_eq!(parsed.proxy.port, Some(4444));
        assert_eq!(parsed.compression_level, 0.5);
        assert!(parsed.debug_log);
        assert_eq!(
            parsed.proxy.upstreams.get("anthropic").map(String::as_str),
            Some("https://upstream.example")
        );
    }

    /// G3: uncommenting any one commented-out key, alone, sets that key —
    /// with nothing set, and with a sub-table (`[proxy.upstreams]`) present.
    #[test]
    fn each_commented_key_works_once_uncommented_alone() {
        let schema = ConfigSchema::generate();
        let mut partly = Config::default();
        partly.proxy.enabled = Some(true);
        partly.proxy.upstreams.insert(
            "anthropic".to_string(),
            "http://127.0.0.1:11434".to_string(),
        );
        for cfg in [Config::default(), partly] {
            let rendered = render_annotated_config(&cfg, &schema);
            let before = toml::to_string(&cfg).unwrap();
            let mut tried = 0;
            for (i, line) in rendered.lines().enumerate() {
                let Some(rest) = line.strip_prefix("# ") else {
                    continue;
                };
                let Some((key, ty)) = rest.split_once(" = <") else {
                    continue;
                };
                let sample = match ty.trim_end_matches('>') {
                    "bool" => "true",
                    "u16" => "4445",
                    "u64" => "30",
                    "f64" => "0.5",
                    "string" => "\"http://127.0.0.1:1\"",
                    "string[]" => "[\"x\"]",
                    other => panic!("no sample value for type {other}"),
                };
                let edited: String = rendered
                    .lines()
                    .enumerate()
                    .map(|(j, l)| {
                        if j == i {
                            format!("{key} = {sample}\n")
                        } else {
                            format!("{l}\n")
                        }
                    })
                    .collect();
                let parsed: Config = toml::from_str(&edited)
                    .unwrap_or_else(|e| panic!("uncommenting `{key}` breaks the file: {e}"));
                assert_ne!(
                    toml::to_string(&parsed).unwrap(),
                    before,
                    "uncommenting `{key}` set nothing"
                );
                tried += 1;
            }
            assert!(tried >= 3, "too few commented keys found:\n{rendered}");
        }
    }

    // Output must be a deterministic function of its inputs and actually
    // carry documentation.
    #[test]
    fn render_is_deterministic_and_annotated() {
        let cfg = Config::default();
        let schema = ConfigSchema::generate();

        let first = render_annotated_config(&cfg, &schema);
        let second = render_annotated_config(&cfg, &schema);

        assert_eq!(first, second, "render must be deterministic");
        assert!(first.contains("# sobre configuration"));
        assert!(
            first.contains("search_roots"),
            "documented keys must appear"
        );
        assert!(
            first.matches("# ").count() > 5,
            "rendered config must be annotated with comments"
        );
    }

    /// C11: every key of the schema appears, set or commented out, and no
    /// environment variable is claimed to override one.
    #[test]
    fn every_key_appears_and_no_env_var_is_claimed() {
        let schema = ConfigSchema::generate();
        let rendered = render_annotated_config(&Config::default(), &schema);
        for (section, s) in &schema.sections {
            for field in s.keys.keys() {
                assert!(
                    rendered.lines().any(|l| {
                        let l = l.trim_start_matches("# ");
                        l.starts_with(&format!("{field} ="))
                    }),
                    "{section}.{field} missing from:\n{rendered}"
                );
            }
        }
        assert!(!rendered.to_lowercase().contains("environment variable"));
        let parsed: toml::Value = toml::from_str(&rendered).expect("still valid TOML");
        let expected: toml::Value =
            toml::from_str(&toml::to_string_pretty(&Config::default()).unwrap()).unwrap();
        assert_eq!(parsed, expected);
    }
}
